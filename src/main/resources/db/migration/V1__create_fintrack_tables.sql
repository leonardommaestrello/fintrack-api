-- 1. USUARIOS
CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(120) NOT NULL,
                         email VARCHAR(180) NOT NULL,
                         senha_hash VARCHAR(255) NOT NULL,
                         criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                         CONSTRAINT uk_usuario_email UNIQUE (email)
);

-- 2. CATEGORIAS
CREATE TABLE categoria (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           usuario_id BIGINT NOT NULL,
                           nome VARCHAR(80) NOT NULL,
                           tipo VARCHAR(10) NOT NULL,
                           cor VARCHAR(7) NOT NULL DEFAULT '#10B981',
                           criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                           CONSTRAINT fk_categoria_usuario
                               FOREIGN KEY (usuario_id)
                                   REFERENCES usuario(id),

                           CONSTRAINT ck_categoria_tipo
                               CHECK (tipo IN ('RECEITA', 'DESPESA')),

                           CONSTRAINT ck_categoria_cor
                               CHECK (cor ~ '^#[0-9A-Fa-f]{6}$'),

    CONSTRAINT uk_categoria_id_usuario_tipo
        UNIQUE (id, usuario_id, tipo)
);

-- 3. TRANSACOES
CREATE TABLE transacao (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           usuario_id BIGINT NOT NULL,
                           categoria_id BIGINT NOT NULL,
                           descricao VARCHAR(200) NOT NULL,
                           valor NUMERIC(15,2) NOT NULL,
                           tipo VARCHAR(10) NOT NULL,
                           data_transacao DATE NOT NULL,
                           criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                           CONSTRAINT fk_transacao_usuario
                               FOREIGN KEY (usuario_id)
                                   REFERENCES usuario(id),

                           CONSTRAINT fk_transacao_categoria
                               FOREIGN KEY (categoria_id, usuario_id, tipo)
                                   REFERENCES categoria(id, usuario_id, tipo),

                           CONSTRAINT ck_transacao_valor
                               CHECK (valor > 0),

                           CONSTRAINT ck_transacao_tipo
                               CHECK (tipo IN ('RECEITA', 'DESPESA'))
);

-- 4. INDICES
CREATE UNIQUE INDEX uk_categoria_usuario_nome_tipo
    ON categoria (
                  usuario_id,
                  tipo,
                  LOWER(TRIM(nome))
        );

CREATE INDEX idx_categoria_usuario
    ON categoria(usuario_id);

CREATE INDEX idx_transacao_usuario_data
    ON transacao(usuario_id, data_transacao DESC);

CREATE INDEX idx_transacao_categoria
    ON transacao(categoria_id);
